def run(
    path_partition_path: Path,
    min_k: int,
    max_k: int,
    trace_depth: int,
    branch_options: int,
    required_signature_power: float,
) -> dict[str, Any]:
    """运行决策树公式路由。"""
    path_partition = load_json(path_partition_path)
    rows = [
        trace_budget_row(k, trace_depth, branch_options, required_signature_power)
        for k in range(min_k, max_k + 1)
    ]
    all_trace_budget_rows_suffice = all(row["trace_budget_suffices"] for row in rows)
